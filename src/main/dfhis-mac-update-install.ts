import { rm, writeFile } from 'node:fs/promises'
import path from 'node:path'

import type { UpdateStatus } from '../shared/types'

export type MacUpdateInstallDeps = {
  getInstallBundlePath: () => string
  extractAppArchive: (archivePath: string, destDir: string) => Promise<void>
  /** Queue a script that survives this process (launchd job on macOS). */
  submitDetachedInstaller: (args: { label: string; scriptPath: string }) => Promise<void>
  quitApp: () => void
  revealPath: (target: string) => void
  showInstallInstructions: (message: string) => Promise<void>
  sendStatus: (status: UpdateStatus) => void
}

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

/**
 * Why: the running bundle cannot be replaced from inside the app. This script is
 * queued as a launchd job, waits for Orca to exit, swaps the bundle, clears the
 * attributes macOS adds to downloaded archives, and reopens the new version.
 */
export function buildMacReplacementScript(args: {
  version: string
  newAppPath: string
  installAppPath: string
  logPath: string
}): string {
  const expected = shellQuote(args.version)
  const newApp = shellQuote(args.newAppPath)
  const installApp = shellQuote(args.installAppPath)
  return `#!/bin/zsh
# Generated by the Orca DFHIS updater; delete after the swap.
set -u
LOG=${shellQuote(args.logPath)}
NEW_APP=${newApp}
INSTALL_APP=${installApp}
EXPECTED_VERSION=${expected}
exec >>"$LOG" 2>&1
echo "[$(date '+%F %T')] installing $EXPECTED_VERSION"
# Why: CLI and daemon children keep the bundle path in their command line, so a
# bundle-wide pgrep never clears; only the GUI main process (binary, no args) blocks.
gui_running() {
  ps -axo command= | sed 's/[[:space:]]*$//' | grep -Fxq "$INSTALL_APP/Contents/MacOS/Orca"
}
for _ in {1..900}; do
  gui_running || break
  sleep 1
done
sleep 1
if gui_running; then
  echo "timed out waiting for Orca to exit"
  exit 1
fi
if [ ! -d "$NEW_APP" ]; then
  echo "missing new app: $NEW_APP"
  exit 1
fi
actual=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$NEW_APP/Contents/Info.plist" 2>/dev/null || true)
if [ "$actual" != "$EXPECTED_VERSION" ]; then
  echo "version mismatch: expected $EXPECTED_VERSION got $actual"
  exit 1
fi
stamp=$(date +%Y%m%d-%H%M%S)
if [ -d "$INSTALL_APP" ]; then
  mkdir -p "$HOME/.Trash"
  mv "$INSTALL_APP" "$HOME/.Trash/Orca.app.before-$stamp" || exit 1
fi
ditto "$NEW_APP" "$INSTALL_APP" || { echo "ditto failed"; exit 1; }
xattr -cr "$INSTALL_APP" 2>/dev/null || true
xattr -rd com.apple.provenance "$INSTALL_APP" 2>/dev/null || true
open "$INSTALL_APP"
echo "[$(date '+%F %T')] done"
`
}

/**
 * Stage the downloaded zip and queue the detached replacement. Falls back to the
 * manual Finder instructions when launchd refuses the job (sandboxed/managed Mac).
 */
export async function installDfhisUpdateOnMac(
  args: { version: string; filePath: string },
  deps: MacUpdateInstallDeps
): Promise<void> {
  const destDir = path.join(path.dirname(args.filePath), 'app')
  await rm(destDir, { recursive: true, force: true })
  await deps.extractAppArchive(args.filePath, destDir)
  const newAppPath = path.join(destDir, 'Orca.app')
  try {
    const scriptPath = path.join(path.dirname(args.filePath), 'install-update.zsh')
    await writeFile(
      scriptPath,
      buildMacReplacementScript({
        version: args.version,
        newAppPath,
        installAppPath: deps.getInstallBundlePath(),
        logPath: path.join(path.dirname(args.filePath), 'install-update.log')
      }),
      { mode: 0o700 }
    )
    await deps.submitDetachedInstaller({
      label: `com.stablyai.orca.dfhis-install-${args.version.replace(/[^A-Za-z0-9.-]/g, '-')}`,
      scriptPath
    })
    // Why: a modal here blocks quitApp until the user dismisses it, so the swap never starts.
    deps.sendStatus({ state: 'idle' })
    deps.quitApp()
  } catch (error) {
    deps.revealPath(newAppPath)
    await deps.showInstallInstructions(
      `自动安装未能启动（${error instanceof Error ? error.message : String(error)}）。请在 Finder 中将 Orca.app 拖入「应用程序」文件夹替换旧版本（替换前请先退出 Orca）。`
    )
    deps.sendStatus({ state: 'idle' })
  }
}
